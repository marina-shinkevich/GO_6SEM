package main

import (
	"fmt"
	"net/http"
	"time"
)

// handler — это функция-обработчик, которая будет вызываться при каждом HTTP-запросе к серверу.
// Важно для экзамена: net/http автоматически вызывает эту функцию в новой отдельной горутине (goroutine) для каждого клиента!
func handler(w http.ResponseWriter, r *http.Request) {
	// 1. Генерируем уникальный ID для текущего запроса на основе текущего времени (в наносекундах).
	id := time.Now().UnixNano()

	// 2. Вывод в стандартный поток (на консоль сервера).
	// Используем пакет fmt для логирования начала обработки конкретного запроса.
	fmt.Printf("%d:start\n", id)

	// 3. Искусственная задержка (имитация долгой работы, например, обращения к БД или долгого вычисления).
	// Именно эта задержка доказывает параллельность: пока один запрос "спит", сервер будет продолжать принимать другие.
	time.Sleep(3 * time.Second)

	// 4. Отправка ответа клиенту (в браузер или curl).
	// Метод Fprint из пакета fmt позволяет писать прямо в поток ответа (w).
	fmt.Fprint(w, "Hello world!")

	// 5. Вывод в консоль информации о завершении обработки этого запроса.
	fmt.Printf("%d:end\n", id)
}

func main() {
	// Регистрируем наш обработчик. Говорим маршрутизатору:
	// "Все запросы на корневой адрес ("/") передавай в функцию handler".
	http.HandleFunc("/", handler)

	// Выводим информационное сообщение в консоль перед стартом.
	fmt.Println("Server started on localhost:3000")

	// Запускаем прослушивание порта 3000.
	// Второй параметр nil означает, что используется стандартный мультиплексор (маршрутизатор) DefaultServeMux.
	// Эта функция блокирует дальнейшее выполнение программы, пока сервер работает.
	http.ListenAndServe("localhost:3000", nil)
}
